"""
output_formatter.py - Color-coded table + overall assessment + LLM summaries.
"""
from __future__ import annotations
from score_extractor import ScoreTable
from config.settings import SECTION_MAP, SCORE_LABELS

_COLOUR_DOT = {"red": "🔴", "yellow": "🟡", "green": "🟢"}

def _section_label(prefix):
    return SECTION_MAP.get(prefix, prefix)

def _pct(n, total):
    return f"{n / total * 100:.0f}%" if total else "0%"

def build_score_table(score_table):
    lines = [
        "| Status | Technical Area | Indicator | Score | Capacity Level |",
        "|:------:|:--------------|:----------|:-----:|:---------------|",
    ]
    sections = score_table.by_section()
    for section_key in sorted(sections.keys()):
        indicators = sorted(sections[section_key], key=lambda i: i.code)
        section_name = _section_label(section_key)
        for ind in indicators:
            dot = _COLOUR_DOT[ind.colour]
            level = SCORE_LABELS.get(ind.score, "—")
            lines.append(f"| {dot} | {section_name} | {ind.code} {ind.name} | **{ind.score}** | {level} |")
    return "\n".join(lines)

def build_overall_assessment(score_table):
    stats = score_table.summary_stats()
    sections = score_table.by_section()
    total = stats["total_indicators"]
    r, y, g = stats["red_count"], stats["yellow_count"], stats["green_count"]
    bar_parts = []
    if g: bar_parts.append(f"🟢 **{g}** green ({_pct(g, total)})")
    if y: bar_parts.append(f"🟡 **{y}** yellow ({_pct(y, total)})")
    if r: bar_parts.append(f"🔴 **{r}** red ({_pct(r, total)})")
    distribution = " · ".join(bar_parts)
    strong_sections, weak_sections = [], []
    for section_key, indicators in sorted(sections.items()):
        section_name = _section_label(section_key)
        reds = [i for i in indicators if i.colour == "red"]
        greens = [i for i in indicators if i.colour == "green"]
        n = len(indicators)
        avg = sum(i.score for i in indicators) / n if n else 0
        if reds:
            red_names = ", ".join(i.code for i in reds)
            weak_sections.append(f"- **{section_name}** — {len(reds)}/{n} indicator{'s' if len(reds)>1 else ''} at score 1 ({red_names})")
        if len(greens) == n:
            strong_sections.append(f"- **{section_name}** — all {n} indicator{'s' if n>1 else ''} at score 4–5 (avg {avg:.1f})")
        elif len(greens) > n / 2:
            strong_sections.append(f"- **{section_name}** — {len(greens)}/{n} indicators at score 4–5 (avg {avg:.1f})")
    parts = [f"**{total} indicators** assessed · Mean score: **{stats['mean_score']}/5**", "", distribution]
    if strong_sections:
        parts += ["", "**Strong capacity across:**"] + strong_sections
    if weak_sections:
        parts += ["", "**Critical gaps in:**"] + weak_sections
    return "\n".join(parts)

def format_document(country, score_table, llm_summary, model="", prompt_tokens=0, completion_tokens=0, latency=0.0):
    doc = [
        f"# JEE Summary: {country}", "", "---", "",
        "## Score Overview", "", build_score_table(score_table), "",
        "> 🔴 Score 1 = No capacity · 🟡 Score 2–3 = Limited/Developed · 🟢 Score 4–5 = Demonstrated/Sustainable",
        "", "---", "",
        "## Overall Assessment", "", build_overall_assessment(score_table), "",
        "---", "",
        "## Section Summaries", "", llm_summary, "",
        "---", "",
        f"*Generated by JEE Summarisation Pipeline · Model: {model} · Tokens: {prompt_tokens} in / {completion_tokens} out · Latency: {latency}s*",
    ]
    return "\n".join(doc)
